// server/http/static.js — the static file server (routes.js hands it every GET / HEAD that is not an API route):
// (i18n-ignore-file: the error pages are bilingual by design, 中文 · English — docs/I18N.md)
//
//     /        → public/      (index.html for directories)
//     /data/   → data/        (generated game data)
//     /shared/ → shared/      (ESM shared with the browser)
//     /sim/    → server/sim/  (the battle simulation, read-only, `.js` only — client-side
//                              combat, DESIGN §14; the Node-only loader nodeData.js is not served)
//     /data.js → a generated browser stand-in of server/data.js (the sim's content modules
//                import `../../../data.js`; in the browser it serves the data injected with
//                /sim/simdata.js setSimData). No other server file is ever served.
//     /media/bgm/act1 → public/assets/audio/bgm/act1.mp3 — the same audio files, addressed
//                **without** an extension so download managers (IDM / 迅雷 …) stop popping a
//                "下载文件信息" dialog for every BGM track (media.js, shared/media.js, public/js/media.js)
//     /packs/index.json → the content packs of this server (server/packs.js: the language packs of
//                public/i18n/ and the pack folders of packs/, re-read when they change; never cached)
//     /packs/<id>/<file> → a file of a pack folder — only one its manifest names (server/packs.js servable)
//     /assets/~<hash>/…, /fonts/~<hash>/…, /media/~<hash>/… → the same files: the content-hash segment
//                (shared/assetPaths.js) is stripped. A hash that names the file's current bytes (assetIndex.js
//                urlHashOk: its own hash, or its Spine model's) answers `immutable` for a year; any other hash —
//                an old page, a URL derived from another file's — the current file with `no-cache`. A segment the
//                STRICT rule does not recognise (not exactly 16 lower-case hex, e.g. a page from a build that issued
//                shorter hashes) is retried without it after the plain path 404s, so a stale tab keeps its art
//                instead of losing every image (stripHashLikeSegment)
//     /data/assets.json, /data/local-assets.json → the served manifests (assetViews.js: every art URL with its
//                content-hash segment; no-cache, the ETag of the view) once the asset index is ready, the files as
//                they are before that or without an index
//     `/assets|fonts|media/…?v=…` → the same files with a validated `v` (D022): immutable for a year, and a `?rv=sha256`
//                URL (runtimeCache.js) answers the pinned content of that version; a code/data file the pinned version
//                cannot resolve is refused to the page's reload path
//     /data.js → a generated browser stand-in of server/data.js with the same runtime versioning as the page's modules
//
// Files under public/assets/ and public/fonts/ get their content hash as ETag when the index has it (a file whose
// size or mtime changed since asks for a rescan), others size + mtime. Traversal & dotfile protection, a directory
// without its trailing slash → 301, 404 page; an absent data/local-assets.json is answered with an empty manifest.
// Files go out through files.js serveFile.

import fsp from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { MEDIA_PREFIX } from '../../shared/media.js';
import { splitHashedPath, HASHED_ROOTS } from '../../shared/assetPaths.js';
import { ROOT, noopLog } from './config.js';
import { sendError, sendJson } from './common.js';
import { MIME, CompressCache, serveBuffer, serveFile } from './files.js';
import { RuntimeCache } from './runtimeCache.js';
import { ASSET_INDEX_ROOTS, hashedFileOpts } from './assetIndex.js';
import { serveMedia } from './media.js';
import { createPackRegistry } from '../packs.js';
import { PACKS_URL, PACK_INDEX_FILE } from '../../shared/packs.js';

/** Browser stand-in of server/data.js, served at /data.js (see the header). Served byte for byte: its first line names the entry, server/index.js. */
export const DATA_SHIM_JS = `// Generated by server/index.js — browser stand-in for server/data.js (DESIGN §14 client-side combat).
// The simulation's content modules (/sim/content/support/index.js) import getData() from here; it returns the game data
// the page injected with /sim/simdata.js setSimData(data).
import { getSimData } from './sim/simdata.js';
export function getData() { return getSimData() || {}; }
export function resetData() {}
`;
/** Files under server/sim that are never served (Node-only). */
const SIM_PRIVATE = new Set(['nodedata.js']); // lower-case (compared case-insensitively)

// ---------------------------------------------------------------------------------------------------
// Static file handler
// ---------------------------------------------------------------------------------------------------

/** Optional per-machine art manifest (tools/local-extract) and the empty stand-in served when it is absent. */
const LOCAL_ART_MANIFEST = 'local-assets.json';
const EMPTY_LOCAL_ART = Buffer.from(JSON.stringify({ version: 1, source: 'none', count: 0, groups: {} }));

/**
 * Create the static request handler.
 * @param {{ publicDir: string, dataDir: string, sharedDir: string, simDir?: string, packsDir?: string,
 *   packs?: ReturnType<typeof createPackRegistry>, runtimeCache?: boolean, log?: object,
 *   assetIndex?: ReturnType<typeof import('./assetIndex.js').createAssetIndex> | null,
 *   views?: ReturnType<typeof import('./assetViews.js').createManifestViews> | null }} dirs
 *   packs: the server's pack registry (default: one over publicDir, dataDir and packsDir — ROOT/packs);
 *   assetIndex / views: the content hashes and the served manifests (none: plain URLs, size-mtime ETags);
 *   runtimeCache: the per-version runtime directory of D022 (default on, SP_HTTP_RUNTIME_CACHE=0 turns it off)
 * @returns {(req: import('node:http').IncomingMessage, res: import('node:http').ServerResponse, rawPath: string, query: string) => Promise<void>}
 */
export function createStaticHandler({ publicDir, dataDir, sharedDir, simDir = path.join(ROOT, 'server', 'sim'), packsDir = path.join(ROOT, 'packs'), packs = null, runtimeCache, log = noopLog,
  assetIndex = null, views = null }) {
  const registry = packs || createPackRegistry({ publicDir, dataDir, packsDir }, { log: /** @type {any} */ (log) });
  const mounts = [
    { prefix: '/data/', name: 'data', dir: path.resolve(dataDir) },
    { prefix: '/shared/', name: 'shared', dir: path.resolve(sharedDir) },
    // the simulation: ES modules only (no directory listings, no other file types, no Node-only loader)
    { prefix: '/sim/', name: 'sim', dir: path.resolve(simDir), only: new Set(['.js']), deny: SIM_PRIVATE },
    { prefix: '/', name: 'public', dir: path.resolve(publicDir) },
  ];
  const shimBody = Buffer.from(DATA_SHIM_JS);
  const shimTag = `shim-${createHash('sha256').update(shimBody).digest('hex')}`;
  const gzipCache = new CompressCache(); // brotli and gzip bodies (files.js)
  const runtime = new RuntimeCache({ publicDir, dataDir, sharedDir, simDir, shimBody, enabled: runtimeCache });
  const immutable = 'public, max-age=31536000, immutable';
  const stale = (req, res) => sendError(req, res, 409, '页面资源版本已变化，请刷新页面 · Runtime version changed, reload');

  return async function serveStatic(req, res, rawPath, query) {
    let decoded;
    try { decoded = decodeURIComponent(rawPath); } catch { sendError(req, res, 400, '请求地址无效 · Bad request'); return; }
    if (!decoded.startsWith('/') || decoded.includes('\0') || decoded.includes('\\')) {
      sendError(req, res, 400, '请求地址无效 · Bad request');
      return;
    }
    // Kept for the lenient retry below: a 404 must be able to re-resolve the file from the ORIGINAL path.
    const rawDecoded = decoded;
    // /assets/~<hash>/x → /assets/x (the hash decides the cache policy below)
    const hashed = splitHashedPath(decoded);
    let urlHash = hashed.hash;
    decoded = hashed.path;
    // A page from an earlier build can ask for a hash this server no longer issues (a different length), and the strict
    // rule above leaves such a segment in the path, where it names a directory that does not exist — every image and
    // every audio file on that page then 404s, which reads as a broken feature rather than a stale tab. Drop it here,
    // BEFORE the routes, so /assets and the extension-less /media route both get the file.
    if (!urlHash) {
      const lenientPath = stripHashLikeSegment(rawDecoded);
      if (lenientPath) decoded = lenientPath;   // urlHash stays null ⇒ `no-cache`, never a year of immutable
    }
    if (decoded === '/data.js') {
      const version = await runtime.version(decoded, query);
      if (version === false) { stale(req, res); return; }
      // Both branches answer these exact bytes (`shimBody`; runtime.body returns it for the shim's own catalog entry),
      // so one content-derived ETag validates either URL.
      await serveBuffer(req, res, { body: shimBody, hash: shimTag, type: MIME['.js'],
        cacheControl: version ? immutable : 'no-cache', cache: gzipCache });
      return;
    }
    // Content packs (server/packs.js): the live index, and only the files a pack's manifest names
    if (decoded.startsWith(PACKS_URL)) {
      const parts = decoded.slice(PACKS_URL.length).split('/');
      if (parts.length === 1 && parts[0] === PACK_INDEX_FILE) { sendJson(req, res, 200, registry.index()); return; }
      const abs = parts.length >= 2 && !parts.some((s) => s === '' || s === '.' || s === '..') ? registry.servable(parts[0], parts.slice(1).join('/')) : null;
      const st = abs ? await fsp.stat(abs).catch(() => null) : null;
      if (!st || !st.isFile()) { sendError(req, res, 404, '页面不存在 · Not found', decoded.length <= 200 ? decoded : ''); return; }
      await serveFile(req, res, abs, st, 'packs', parts, query, gzipCache, log);
      return;
    }
    // Extension-less audio (download-manager avoidance): /media/bgm/act1 → /assets/audio/bgm/act1.mp3
    if (decoded.startsWith(MEDIA_PREFIX)) {
      await serveMedia(req, res, decoded.slice(MEDIA_PREFIX.length), query, publicDir, gzipCache, log, { urlHash, assetIndex });
      return;
    }
    // The served manifests: every art URL with its content hash (assetViews.js), once the index is ready
    if (views && (decoded === '/data/assets.json' || decoded === '/data/local-assets.json')) {
      const view = await views.get(decoded.slice('/data/'.length));
      if (view) {
        await serveBuffer(req, res, { body: view.body, hash: view.hash, type: MIME['.json'], cacheControl: 'no-cache', key: `view:${decoded}`, cache: gzipCache });
        return;
      }
    }
    // Bare mount paths (e.g. "/data") → treat as the mount directory.
    const mount = mounts.find((m) => decoded.startsWith(m.prefix) || decoded === m.prefix.slice(0, -1)) || mounts[mounts.length - 1];
    const rest = decoded.length > mount.prefix.length ? decoded.slice(mount.prefix.length) : '';
    const segments = rest.split('/').filter((s) => s.length > 0);
    if (segments.some((s) => s === '..' || s === '.')) { sendError(req, res, 403, '禁止访问 · Forbidden'); return; }
    if (segments.some((s) => s.startsWith('.'))) { sendError(req, res, 404, '页面不存在 · Not found'); return; }
    if (mount.only && (!segments.length || !mount.only.has(path.extname(segments[segments.length - 1]).toLowerCase())
      // (case-insensitive: the host may be Windows / macOS, where NODEDATA.JS opens nodeData.js)
      || (mount.deny && mount.deny.has(segments[segments.length - 1].toLowerCase())))) {
      sendError(req, res, 404, '页面不存在 · Not found');
      return;
    }
    let absPath = path.join(mount.dir, ...segments);
    if (absPath !== mount.dir && !absPath.startsWith(mount.dir + path.sep)) { sendError(req, res, 403, '禁止访问 · Forbidden'); return; }

    let stat;
    let viaDirectory = false;
    try {
      stat = await fsp.stat(absPath);
      if (stat.isDirectory()) {
        if (!decoded.endsWith('/')) {
          // Built from normalized segments (never from the raw path) so "//host" can't become an open redirect.
          const loc = (mount.prefix + segments.map(encodeURIComponent).join('/') + '/').replace(/\/{2,}/g, '/');
          res.writeHead(301, { Location: loc + (query ? `?${query}` : ''), 'Cache-Control': 'no-cache', 'Content-Length': 0 });
          res.end();
          return;
        }
        absPath = path.join(absPath, 'index.html');
        segments.push('index.html');
        viaDirectory = true;
        stat = await fsp.stat(absPath);
      }
      // Not a regular file, or a file addressed like a directory ("/app.js/") → 404.
      if (!stat.isFile() || (decoded.endsWith('/') && !viaDirectory)) {
        throw Object.assign(new Error('not a file'), { code: 'ENOENT' });
      }
      if (mount.deny) {
        // the on-disk name decides (case-insensitive file systems, Windows 8.3 short names like NODEDA~1.JS)
        const real = await fsp.realpath(absPath);
        if (mount.deny.has(path.basename(real).toLowerCase())) throw Object.assign(new Error('private'), { code: 'ENOENT' });
      }
    } catch (e) {
      if (e && e.code === 'ENOENT' && mount.name === 'data' && segments.length === 1 && segments[0] === LOCAL_ART_MANIFEST) {
        // Optional local-client art (DESIGN §13): an install without it gets an empty manifest instead of a 404,
        // so browsers don't log an error on every page load. Clients treat empty groups as "no local art".
        if (new URLSearchParams(query).has('rv')) { stale(req, res); return; }
        res.writeHead(200, { 'Content-Type': MIME['.json'], 'Cache-Control': 'no-cache', 'Content-Length': EMPTY_LOCAL_ART.length });
        res.end(req.method === 'HEAD' ? undefined : EMPTY_LOCAL_ART);
      } else if (e && (e.code === 'ENOENT' || e.code === 'ENOTDIR' || e.code === 'EISDIR' || e.code === 'ENAMETOOLONG')) {
        // A stale page's hash segment (a different length than this build issues) names a directory that does not
        // exist. Retry once with any `~…` first segment dropped, so an older page keeps its art instead of losing
        // every image — see stripHashLikeSegment. The response is no-cache: this URL is not backed by a hash we know.
        const lenient = stripHashLikeSegment(rawDecoded);
        if (lenient && lenient !== decoded) {
          const m2 = mounts.find((m) => lenient.startsWith(m.prefix) || lenient === m.prefix.slice(0, -1)) || mounts[mounts.length - 1];
          const segs2 = (lenient.length > m2.prefix.length ? lenient.slice(m2.prefix.length) : '').split('/').filter((s) => s.length > 0);
          if (!segs2.some((s) => s === '..' || s === '.' || s.startsWith('.'))) {
            const abs2 = path.join(m2.dir, ...segs2);
            if (abs2 === m2.dir || abs2.startsWith(m2.dir + path.sep)) {
              const st2 = await fsp.stat(abs2).catch(() => null);
              if (st2 && st2.isFile()) {
                await serveFile(req, res, abs2, st2, m2.name, segs2, query, gzipCache, log, { cacheControl: 'no-cache' });
                return;
              }
            }
          }
        }
        sendError(req, res, 404, '页面不存在 · Not found', decoded.length <= 200 ? decoded : '');
      } else if (e && (e.code === 'EACCES' || e.code === 'EPERM')) {
        sendError(req, res, 403, '禁止访问 · Forbidden');
      } else {
        log.error('[http] stat failed', e);
        sendError(req, res, 500, '服务器内部错误 · Internal error');
      }
      return;
    }
    const version = await runtime.version(decoded, query);
    if (version === false) { stale(req, res); return; }
    if (version) {
      const body = await runtime.body(version, stat);
      if (!body) { stale(req, res); return; }
      await serveBuffer(req, res, { body, tag: `rv-${version.hash}`,
        type: MIME[path.extname(absPath).toLowerCase()] || 'application/octet-stream',
        cacheControl: immutable, mtime: stat.mtime, cache: gzipCache });
      return;
    }
    if (mount.name === 'public' && absPath === path.join(mount.dir, 'index.html')) {
      let rendered;
      try { rendered = await runtime.renderIndex(absPath); }
      catch (error) { log.warn?.('[http] runtime cache unavailable, serving revalidated HTML', error.message); }
      if (rendered) {
        // Only a content ETag validates generated HTML: index.html's mtime alone cannot detect a data-only update.
        await serveBuffer(req, res, { body: rendered.body, tag: rendered.tag, type: MIME['.html'], cache: gzipCache });
        return;
      }
    }
    // The content hashes (assetIndex.js) and the hash-segment cache policy of the art URLs (static.js header)
    const indexed = mount.name === 'public' && segments.length > 1 && ASSET_INDEX_ROOTS.includes(segments[0]);
    const opts = indexed ? hashedFileOpts(assetIndex, segments.join('/'), stat, urlHash) : (urlHash ? { cacheControl: 'no-cache' } : {});
    await serveFile(req, res, absPath, stat, mount.name, segments, query, gzipCache, log, opts);
  };
}

/**
 * Drop a `~<something>` first segment from an asset URL, whatever its length or case.
 *
 * `splitHashedPath` (shared/assetPaths.js) strips only a WELL-FORMED segment — exactly `~` + 16 lower-case hex — and
 * leaves anything else in the path, which is right for building and validating URLs. But a browser holding an older
 * page can ask for a hash this server no longer issues: the same file's hash may differ in length after a rebuild (a
 * stale tab asked for `~99367b3` while the running server issues `~5328a27f599367b3`). A segment the strict rule does
 * not recognise stays in the path, names a directory that does not exist, and answers 404 — so every image on that
 * page fails, which reads as a broken feature rather than a stale tab.
 *
 * Used ONLY as a retry after the plain path already answered 404 (see the catch in `serveStatic`), so a real file
 * whose name happens to start with `~` is still served first and this can never shadow it.
 * @param {string} path the ORIGINAL decoded path (before `splitHashedPath` touched it)
 * @returns {string|null} the path without that segment, or null when there is nothing to drop
 */
export function stripHashLikeSegment(path) {
  const p = String(path ?? '');
  for (const root of HASHED_ROOTS) {
    if (!p.startsWith(root)) continue;
    const slash = p.indexOf('/', root.length);
    if (slash < 0) break;
    const seg = p.slice(root.length, slash);
    // hash-like: `~`, then ASCII letters/digits only, ending in a hex digit
    if (!/^~[0-9A-Za-z]+$/.test(seg) || !/[0-9a-fA-F]$/.test(seg)) break;
    const rest = p.slice(slash + 1);
    return rest ? root + rest : null;   // never turn "/assets/~x//" into the bare root
  }
  return null;
}
